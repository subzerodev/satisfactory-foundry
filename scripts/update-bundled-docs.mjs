#!/usr/bin/env node
// update-bundled-docs.mjs — refresh the bundled default catalog snapshot.
//
// Reads a Satisfactory Docs file (UTF-16 LE + BOM as the game ships it),
// re-encodes it to BOM-less UTF-8, validates it through the production parser,
// and writes it to public/bundled-docs/ alongside a provenance sidecar. The
// app fetches these at boot as its default catalog (ticket #9); re-run this
// after a game patch to refresh the snapshot.
//
// Usage:
//   node --experimental-strip-types scripts/update-bundled-docs.mjs [docsPath] [--build N]
//
//   (Node >= 23.6 strips TypeScript by default, so plain `node scripts/...`
//    works too; the flag is kept for older nodes that need it.)
//
//   docsPath  Path to the game's en-US.json (default: the local Steam install).
//   --build N Override the Steam build id (default: read from the appmanifest;
//             required if the appmanifest is not found).
//
// It refuses to overwrite the asset if the file does not parse cleanly.

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve, join } from "node:path";

import { decodeBytes } from "../src/ui/decode.ts";
import { parseCatalogFromText } from "../src/data/catalog.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, "..");

// The user's local Steam install (decision #9 snapshot source).
const DEFAULT_DOCS_PATH =
  "/home/subzerodev/.local/share/Steam/steamapps/common/Satisfactory/CommunityResources/Docs/en-US.json";
const APPMANIFEST_PATH =
  "/home/subzerodev/.local/share/Steam/steamapps/appmanifest_526870.acf";

const OUT_DIR = join(REPO_ROOT, "public", "bundled-docs");

function parseArgs(argv) {
  let docsPath = DEFAULT_DOCS_PATH;
  let build;
  const rest = argv.slice(2);
  for (let i = 0; i < rest.length; i++) {
    const arg = rest[i];
    if (arg === "--build") {
      build = rest[++i];
    } else if (arg.startsWith("--build=")) {
      build = arg.slice("--build=".length);
    } else if (!arg.startsWith("--")) {
      docsPath = arg;
    }
  }
  return { docsPath, build };
}

/** Read the Steam build id from the appmanifest, or undefined if unavailable. */
async function readSteamBuild() {
  try {
    const text = await readFile(APPMANIFEST_PATH, "utf-8");
    // The .acf is a Valve KeyValues file: `"buildid"   "23855724"`.
    const match = text.match(/"buildid"\s+"(\d+)"/);
    return match ? match[1] : undefined;
  } catch {
    return undefined;
  }
}

async function main() {
  const { docsPath, build: buildOverride } = parseArgs(process.argv);

  const steamBuild = buildOverride ?? (await readSteamBuild());
  if (!steamBuild) {
    console.error(
      "error: could not resolve the Steam build id from the appmanifest; " +
        "pass --build <N> explicitly.",
    );
    process.exit(1);
  }

  // Decode the game's UTF-16 file via the SAME decoder the upload path uses.
  const bytes = await readFile(docsPath);
  const text = decodeBytes(new Uint8Array(bytes));

  // Validate by running the production parser. A parse failure aborts BEFORE
  // any write, so a bad input never clobbers a good snapshot.
  let catalog;
  try {
    catalog = parseCatalogFromText(text);
  } catch (err) {
    console.error(
      `error: ${docsPath} did not parse — refusing to write.\n  ${
        err instanceof Error ? err.message : String(err)
      }`,
    );
    process.exit(1);
  }

  const items = Object.keys(catalog.items).length;
  const recipes = Object.keys(catalog.recipes).length;
  const extractedAt = new Date().toISOString().slice(0, 10); // ISO date

  await mkdir(OUT_DIR, { recursive: true });

  // Write the catalog text as BOM-less UTF-8: JSON.parse rejects a leading BOM
  // and fetch().text() does not strip one, so the boot path must get clean UTF-8.
  await writeFile(join(OUT_DIR, "en-US.json"), text, "utf-8");

  const provenance = {
    source: "local Steam install",
    steamBuild,
    extractedAt,
    items,
    recipes,
    note:
      "Generated by scripts/update-bundled-docs.mjs from the local Satisfactory " +
      "Docs.json. Re-run that script after a game patch to refresh this snapshot.",
  };
  await writeFile(
    join(OUT_DIR, "provenance.json"),
    JSON.stringify(provenance, null, 2) + "\n",
    "utf-8",
  );

  console.log(
    `wrote ${OUT_DIR}/en-US.json + provenance.json — ` +
      `Steam build ${steamBuild}, ${items} items / ${recipes} recipes, extractedAt ${extractedAt}.`,
  );
}

main();
